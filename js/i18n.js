function t(key) {
  const lang = State?.currentLanguage || 'en';
  return I18N[lang]?.[key] || I18N.en[key] || key;
}

function applyTranslations() {
  const lang = State.currentLanguage;
  document.documentElement.lang = lang === 'am' ? 'am' : 'en';
  document.body.classList.toggle('amharic', lang === 'am');

  // Update all data-i18n elements
  document.querySelectorAll('[data-i18n]').forEach(el => {
    const key = el.getAttribute('data-i18n');
    const translated = t(key);
    if (translated) el.textContent = translated;
  });

  // Update data-i18n-placeholder elements
  document.querySelectorAll('[data-i18n-placeholder]').forEach(el => {
    el.placeholder = t(el.getAttribute('data-i18n-placeholder'));
  });

  // Update nav links text
  document.querySelectorAll('[data-nav]').forEach(el => {
    const key = el.dataset.nav;
    const mapping = { home: 'home', features: 'features', about: 'about', contact: 'contact' };
    if (mapping[key]) el.textContent = t(mapping[key]);
  });

  // Update language toggle labels
  const langLabel = lang === 'en' ? 'EN' : 'አማ';
  document.querySelectorAll('.lang-text').forEach(el => { el.textContent = langLabel; });

  // Update header buttons
  const loginBtn = document.getElementById('navLoginBtn');
  const registerBtn = document.getElementById('navRegisterBtn');
  if (loginBtn) loginBtn.textContent = t('signIn');
  if (registerBtn) registerBtn.textContent = t('getStarted');

  // Update mobile nav buttons
  const mobileLogin = document.getElementById('mobileLoginBtn');
  const mobileRegister = document.getElementById('mobileRegisterBtn');
  if (mobileLogin) mobileLogin.textContent = t('signIn');
  if (mobileRegister) mobileRegister.textContent = t('getStarted');

  // Update auth page if visible
  const authTitle = document.getElementById('authTitle');
  const authSubtitle = document.getElementById('authSubtitle');
  const activeTab = document.querySelector('.auth-tab.active')?.dataset.authTab;
  if (authTitle) authTitle.textContent = activeTab === 'login' ? t('welcomeBack') : t('createAccount');
  if (authSubtitle) authSubtitle.textContent = activeTab === 'login' ? t('signInSubtitle') : t('registerSubtitle');

  // Refresh dashboard if active
  if (State.currentUser && App.currentPage === 'dashboard') {
    Dashboard.updateUserInfo();
    Dashboard.loadSettings();
    Dashboard.loadChildren();
  }
}
